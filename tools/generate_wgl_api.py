#!/usr/bin/env python3
"""Generate the private WGL dispatch table from the shared backend's GL calls."""

import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
backend = root / "src" / "backends" / "opengl"
registry = root / "vendor" / "opengl-registry" / "api" / "GL" / "glcorearb.h"
types = registry.read_text(encoding="utf-8")
names = {"glQueryCounter", "glGetQueryiv"}
for path in backend.glob("*.hpp"):
    if path.name != "wgl_api.hpp":
        names.update(re.findall(r"\bgl[A-Z]\w+", path.read_text(encoding="utf-8")))
names = sorted(name for name in names if f"PFN{name.upper()}PROC" in types)
lines = [
    "#pragma once",
    "",
    "// Generated by tools/generate_wgl_api.py; do not edit.",
    '#include "foundation_backend.hpp"',
    "#include <windows.h>",
    "#include <GL/glcorearb.h>",
    "#include <bit>",
    "#include <cstdint>",
    "",
    "namespace truffle::rhi::detail::gl_probe::wgl_api {",
    "inline PROC resolve(const char* name) {",
    "    auto proc = wglGetProcAddress(name);",
    "    const auto value = reinterpret_cast<std::intptr_t>(proc);",
    "    if (proc == nullptr || value == 1 || value == 2 || value == 3 || value == -1) {",
    '        proc = GetProcAddress(GetModuleHandleW(L"opengl32.dll"), name);',
    "    }",
    "    return proc;",
    "}",
    "",
    "#define TFL_WGL_FUNCTIONS(X) \\",
]
for index, name in enumerate(names):
    suffix = " \\" if index < len(names) - 1 else ""
    lines.append(f"    X(PFN{name.upper()}PROC, {name[2:]}){suffix}")
lines += [
    "",
    "struct Api {",
    "#define TFL_WGL_SLOT(type, name) type name = nullptr;",
    "    TFL_WGL_FUNCTIONS(TFL_WGL_SLOT)",
    "#undef TFL_WGL_SLOT",
    "};",
    "inline thread_local Api* current = nullptr;",
    "",
    "[[nodiscard]] inline Status load(Api& api) {",
    "#define TFL_WGL_LOAD(type, name) \\",
    '    api.name = std::bit_cast<type>(resolve("gl" #name)); \\',
    "    if (api.name == nullptr) { \\",
    '        return Status::failure(StatusCode::unavailable, "WGL requires gl" #name); \\',
    "    }",
    "    TFL_WGL_FUNCTIONS(TFL_WGL_LOAD)",
    "#undef TFL_WGL_LOAD",
    "    return Status::success();",
    "}",
    "#undef TFL_WGL_FUNCTIONS",
    "}",
    "",
]
for name in names:
    lines.append(f"#define {name} (::truffle::rhi::detail::gl_probe::wgl_api::current->{name[2:]})")
with (backend / "wgl_api.hpp").open("w", encoding="utf-8", newline="\n") as output:
    output.write("\n".join(lines) + "\n")
